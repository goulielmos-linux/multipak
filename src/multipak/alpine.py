"""Read Alpine .apk package metadata without unpacking files or running scripts.

Tells Alpine's .PKGINFO apart from Arch's, declines the new apk v3 format, and
estimates the Alpine release from the abuild version that built the package."""

import datetime
import gzip
import re
import tarfile
import zlib
from dataclasses import dataclass
from pathlib import Path

from multipak.localization import tr

GZIP_MAGIC = b"\x1f\x8b"
# "ADB" followed by the compression: "." none, "d" deflate, "c" with a compression spec.
ADB_MAGIC = re.compile(rb"ADB[.dc]")
MAX_METADATA_SCAN = 16 * 1024 * 1024
MAX_METADATA_FILE = 1024 * 1024
# Only signature files come before .PKGINFO.
MAX_CONTROL_MEMBERS = 16
PACKAGE_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9+._-]*")
VERSION = re.compile(r"[0-9][A-Za-z0-9+._~-]*")
ARCHITECTURE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]*")
# Alpine's releases are major.minor: 3.23, 3.24... VERSION_ID adds the patch level.
RELEASE = re.compile(r"[0-9]+\.[0-9]+")
# The development branch, whose VERSION_ID is the next release's: 3.25.0_alpha20260805.
EDGE = "edge"
ABUILD = re.compile(r"#\s*Generated by abuild ([0-9]+)\.([0-9]+)\.[0-9]+(_rc[0-9]+)?")
# abuild 3.<minor> -> the Alpine release whose builders and repositories used it. Taken
# from the "# Generated by abuild" line of 25 random packages per repository (main and
# community) of each branch, v3.10 to edge, on dl-cdn.alpinelinux.org in November 2026.
# A package keeps the abuild of the branch that built it: packages carried unchanged into
# later releases keep an older one, and edge, after a release, still builds with that
# release's abuild until the next release's candidates. abuild 3.9 served two releases:
# its release candidates built 3.15, the final 3.9.0 built 3.16.
ABUILD_RELEASES = {
    4: "3.10",
    5: "3.11",
    6: "3.12",
    7: "3.13",
    8: "3.14",
    9: "3.16",
    10: "3.17",
    11: "3.18",
    12: "3.19",
    13: "3.20",
    14: "3.21",
    15: "3.22",
    16: "3.23",
    17: "3.24",
}
# From abuild 3.10 on, each release is abuild's minor version plus 7.
ABUILD_RELEASE_OFFSET = 7
# End of support of each release, from https://alpinelinux.org/releases.json (November
# 2026). The catalog reads the current file when it can; a release newer than this table
# is supported, an older one is not.
END_OF_SUPPORT = {
    "3.14": "2023-05-01",
    "3.15": "2023-11-01",
    "3.16": "2024-05-23",
    "3.17": "2024-11-22",
    "3.18": "2025-05-09",
    "3.19": "2025-11-01",
    "3.20": "2026-04-01",
    "3.21": "2026-11-01",
    "3.22": "2027-05-01",
    "3.23": "2027-11-01",
    "3.24": "2028-06-01",
}


@dataclass(frozen=True)
class Info:
    name: str
    version: str
    architecture: str
    summary: str
    dependencies: str
    signed: bool
    # The release estimated from the abuild version, such as "3.20"; "" when unknown.
    release: str = ""


def release_version(value: str) -> str:
    """The Alpine release (major.minor) of a VERSION_ID such as 3.24.3, or "edge"."""
    value = value.strip()
    if "_alpha" in value:
        # Edge reports the release it will become: 3.25.0_alpha20260805.
        return EDGE
    match = RELEASE.match(value)
    return match[0] if match else ""


def release_key(release: str) -> tuple[int, ...]:
    return tuple(int(part) for part in release.split("."))


def estimated_release(raw: bytes) -> str:
    """The Alpine release whose abuild built the package, from .PKGINFO's first lines."""
    for line in raw.decode("utf-8", errors="replace").splitlines()[:4]:
        match = ABUILD.match(line.strip())
        if match is None:
            continue
        major, minor = int(match[1]), int(match[2])
        if major != 3:
            return ""
        if minor == 9 and match[3]:
            return "3.15"
        if minor in ABUILD_RELEASES:
            return ABUILD_RELEASES[minor]
        if minor > max(ABUILD_RELEASES):
            return f"3.{minor + ABUILD_RELEASE_OFFSET}"
        return ""
    return ""


def supported(release: str, today: datetime.date, end_of_support=END_OF_SUPPORT) -> bool:
    """Whether Alpine still updates this release (edge always)."""
    if release == EDGE:
        return True
    if not RELEASE.fullmatch(release):
        return False
    end = end_of_support.get(release)
    if end is None:
        known = [release_key(item) for item in end_of_support]
        return not known or release_key(release) > max(known)
    try:
        return today < datetime.date.fromisoformat(end)
    except ValueError:
        return False


def is_v3(header: bytes) -> bool:
    """An apk-tools 3 package (ADB), which MultiPak does not read."""
    return bool(ADB_MAGIC.match(header[:4]))


def v3_error() -> ValueError:
    return ValueError(
        tr(
            "This Alpine package uses the new apk v3 format, which MultiPak cannot read yet. "
            "Use a package in the classic format, like those in Alpine's repositories."
        )
    )


class _MetadataReader:
    """Cap decompression while looking for .PKGINFO near the start of the archive."""

    def __init__(self, source):
        self.source = source
        self.remaining = MAX_METADATA_SCAN

    def read(self, size):
        data = self.source.read(min(size, self.remaining + 1))
        self.remaining -= len(data)
        if self.remaining < 0:
            raise ValueError(tr("Alpine package metadata exceeds the read limit."))
        return data


def _control(path: Path) -> tuple[bytes, bool]:
    """The .PKGINFO member and whether a signature precedes it. Nothing is extracted."""
    signed = False
    try:
        with gzip.open(path, "rb") as stream:
            with tarfile.open(fileobj=_MetadataReader(stream), mode="r|") as archive:
                for index, member in enumerate(archive):
                    name = member.name.removeprefix("./")
                    if index >= MAX_CONTROL_MEMBERS or not name.startswith("."):
                        break
                    if name.startswith(".SIGN."):
                        signed = True
                        continue
                    if name != ".PKGINFO":
                        continue
                    if not member.isfile() or not 0 <= member.size <= MAX_METADATA_FILE:
                        raise ValueError(tr("Invalid Alpine .PKGINFO metadata."))
                    source = archive.extractfile(member)
                    if source is None:
                        raise ValueError(tr("Invalid Alpine .PKGINFO metadata."))
                    return source.read(MAX_METADATA_FILE + 1), signed
    except (tarfile.TarError, OSError, EOFError, zlib.error, RecursionError) as error:
        raise ValueError(tr("The Alpine package could not be read: {0}").format(error)) from error
    raise ValueError(tr("The file does not contain Alpine .PKGINFO metadata."))


def _fields(raw: bytes) -> dict[str, list[str]]:
    fields: dict[str, list[str]] = {}
    for line in raw.decode("utf-8", errors="replace").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, separator, value = line.partition(" = ")
        if not separator or not key.strip():
            raise ValueError(tr("Invalid Alpine .PKGINFO metadata."))
        fields.setdefault(key.strip(), []).append(value.strip())
    return fields


def is_candidate(path: Path, header: bytes) -> bool:
    """A gzip TAR whose control part is Alpine's: signed, or with origin and datahash."""
    if not header.startswith(GZIP_MAGIC):
        return False
    try:
        raw, signed = _control(path)
        fields = _fields(raw)
    except ValueError:
        return False
    if "pkgbase" in fields or "xdata" in fields:
        return False  # Arch Linux
    return signed or ("origin" in fields and "datahash" in fields)


def read_info(path: Path) -> Info:
    """Inspect an Alpine package's .PKGINFO without unpacking its files or scripts."""
    raw, signed = _control(path)
    fields = _fields(raw)
    for key in ("pkgname", "pkgver", "arch"):
        if len(fields.get(key, ())) != 1 or not fields[key][0]:
            raise ValueError(tr("Missing or duplicate Alpine metadata: {0}.").format(key))
    name, version, architecture = (fields[key][0] for key in ("pkgname", "pkgver", "arch"))
    if not PACKAGE_NAME.fullmatch(name):
        raise ValueError(tr("Invalid Alpine package name."))
    if not VERSION.fullmatch(version):
        raise ValueError(tr("Invalid Alpine package version."))
    if not ARCHITECTURE.fullmatch(architecture):
        raise ValueError(tr("Invalid Alpine package architecture."))
    summaries = fields.get("pkgdesc", ())
    summary = " ".join(summaries[0].split()) if summaries else ""
    # One "depend" line per dependency; "!name" marks a conflict, not a requirement.
    dependencies = "\n".join(
        value for value in fields.get("depend", ()) if value and not value.startswith("!")
    )
    return Info(name, version, architecture, summary, dependencies, signed, estimated_release(raw))


def dependency_lines(dependencies: str) -> list[str]:
    """Readable requirements: "so:libX11.so.6" becomes the library name itself."""
    return [line.strip().removeprefix("so:") for line in dependencies.splitlines() if line.strip()]
