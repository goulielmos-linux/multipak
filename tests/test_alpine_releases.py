def test_edge_environment_naming_and_reuse():
    edge = alpine_environment("edge")
    assert container_base(edge) == "MultiPak-Alpine-edge"
    box = ExistingEnvironment("MultiPak-Alpine-edge", "id", "alpine", "edge", "image")
    assert box.matches(edge) and box.multipak_managed
    assert not box.matches(alpine_environment("3.24"))
    assert not ExistingEnvironment("x", "id", "alpine", "3.24", "image").matches(edge)


@pytest.fixture
def alpine_engine(fake_engine):
    fake_engine.runner.release = RELEASE
    return fake_engine


def test_installs_in_an_older_release_and_in_edge(alpine_engine, tmp_path):
    engine = alpine_engine
    tx = install(engine, make_apk(tmp_path / "a.apk"), alpine_environment("3.20"))
    assert (tx.status, tx.container, tx.environment_id) == (
        "installed",
        "MultiPak-Alpine-3.20",
        "alpine-3.20",
    )
    engine.runner.package_present = False
    tx = install(engine, make_apk(tmp_path / "b.apk"), alpine_environment("edge"))
    assert (tx.status, tx.container) == ("installed", "MultiPak-Alpine-edge")
    create = [call for call in engine.runner.calls if call[:2] == ["distrobox", "create"]][-1]
    assert create[create.index("--image") + 1] == "docker.io/library/alpine:edge"


def test_existing_edge_container_is_checked(alpine_engine, tmp_path):
    engine = alpine_engine
    edge = alpine_environment("edge")
    first = install(engine, make_apk(tmp_path / "a.apk"), edge)
    existing = ExistingEnvironment(first.container, "container123", "alpine", "edge", "image123")
    engine.runner.package_present = False
    engine.runner.release = RELEASE.replace("3.24.3", "3.25.0_alpha20260805")
    package = inspect_package(make_apk(tmp_path / "b.apk"), engine.runner)
    assert engine.install(package, edge, existing=existing).status == "installed"
    # A stable release in the container is not edge.
    engine.runner.package_present = False
    engine.runner.release = RELEASE
    with pytest.raises(RuntimeError, match="has changed"):
        engine.install(package, edge, existing=existing)
